export const LANGS = ["en", "tr", "ru"];

export function currentLang() {
  try {
    const stored = localStorage.getItem("lang");
    if (LANGS.includes(stored)) return stored;
  } catch (e) {}
  return LANGS.includes(document.documentElement.lang) ? document.documentElement.lang : "en";
}

export function nextLang(code) {
  const i = LANGS.indexOf(code);
  return LANGS[(i < 0 ? 0 : i + 1) % LANGS.length];
}
