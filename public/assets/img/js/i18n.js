export function langFromTimeZone(zone) {
  if (zone === "Europe/Istanbul" || zone === "Asia/Istanbul") return "tr";
  if (DE_ZONES.has(zone)) return "de";
  if (RU_ZONES.has(zone)) return "ru";
  return "en";
}

export function currentLang() {
  try {
    const stored = localStorage.getItem("lang");
    if (LANGS.includes(stored)) return stored;
  } catch (e) {}
  const docLang = document.documentElement.lang;
  if (LANGS.includes(docLang) && docLang !== "en") return docLang;
  try {
    const fromPlace = langFromTimeZone(Intl.DateTimeFormat().resolvedOptions().timeZone);
    if (fromPlace !== "en") return fromPlace;
  } catch (e) {}
  return LANGS.includes(docLang) ? docLang : "en";
}

export function nextLang(code) {
  const i = LANGS.indexOf(code);
  return LANGS[(i < 0 ? 0 : i + 1) % LANGS.length];
}
